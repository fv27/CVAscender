const slug = (s) => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

export const SCHOOL_ACTIVITIES = SCHOOLS.flatMap((school) => {
  const entry = ACTIVITIES[school.id];
  if (!entry) return [];
  return entry.acts.map(([key, note, over = {}]) => {
    const t = T[key];
    const title = over.title || t.title;
    return {
      id: `${school.id}-${slug(title)}`,
      title, org: school.name, schoolId: school.id,
      type: over.type || t.type, categories: over.categories || t.categories, skills: over.skills || t.skills,
      scope: 'internal', format: 'in-person', city: school.city, canton: school.canton,
      minAge: over.minAge ?? t.minAge ?? 11, maxAge: over.maxAge ?? 19, minYear: over.minYear,
      eligibility: `Students at ${school.name}. Ask at school about places and requirements.`,
      description: over.description || t.description,
      details: `${note} Listed by the school — what is offered can change each year, so check with your teachers.`,
      timing: 'Ask at school — usually at the start of each term',
      commitment: 'Varies — ask at school', cost: over.cost || 'Ask at school',
      url: entry.url || school.url, verified: true, source: entry.src,
    };
  });
});
